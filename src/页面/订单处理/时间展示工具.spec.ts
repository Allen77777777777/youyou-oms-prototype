import { describe, expect, it } from 'vitest'
import { 格式化北京时间, 解析来源时刻, 计算剩余发货时间 } from './时间展示工具'
import type { 订单处理状态 } from '../全渠道订单/类型'

describe('订单处理北京时间投影', () => {
  it('UTC 与不同偏移转换为同一北京时间，跨年仍保留完整日期及秒', () => {
    for (const 时间 of ['2026-09-12 08:21:07 UTC+8', '2026-09-12T00:21:07Z', '2026-09-11T17:21:07-07:00', '2026-09-12 05:51:07 UTC+5:30']) {
      expect(格式化北京时间(时间)).toBe('2026-09-12 08:21:07')
    }
    expect(格式化北京时间('2026-12-31T18:30:00Z')).toBe('2027-01-01 02:30:00')
    expect(格式化北京时间('2026-09-12 08:21 UTC+8')).toBe('2026-09-12 08:21:00')
    expect(格式化北京时间('2026-09-12T00:00:00.123456Z')).toBe('2026-09-12 08:00:00')
    expect(格式化北京时间('2026-09-12 00:00:00 UTC')).toBe('2026-09-12 08:00:00')
  })
  it('缺值为空，无偏移和非法日历不能由运行环境推测或被日期溢出修正', () => {
    for (const 时间 of [undefined, '', ' ', '—']) expect(格式化北京时间(时间)).toBe('—')
    for (const 时间 of ['2026-09-12 08:21:00', '2026-09-12T08:21:00', 'bad', '2026-02-29T00:00:00Z', '2026-02-31T00:00:00Z', '2026-09-12T24:00:00Z', '2026-09-12T08:60:00Z', '2026-09-12T08:00:60Z', '2026-09-12 08:21 UTC+8:60', '2026-09-12T08:00:00+14:01', '2026-09-12T08:00:00-00:00']) {
      expect(解析来源时刻(时间)).toBeUndefined()
      expect(格式化北京时间(时间)).toBe('时间待核实')
    }
    expect(格式化北京时间('2028-02-29T00:00:00Z')).toBe('2028-02-29 08:00:00')
  })
})

describe('剩余发货时间', () => {
  const 截止 = '2026-09-13T10:00:00Z'
  const 截止时刻 = Date.parse(截止)
  it('按完整来源时刻计算，天数与时分秒跨天保留，截止前不足一秒不提前超时', () => {
    expect(计算剩余发货时间(截止, '待审核', 截止时刻 - 90_061_000)).toEqual({ kind: 'remaining', text: '1天 01:01:01' })
    expect(计算剩余发货时间('2026-09-13 18:00:00 UTC+8', '待发货', 截止时刻 - 1)).toEqual({ kind: 'remaining', text: '00:00:01' })
    expect(计算剩余发货时间(截止, '异常', 截止时刻 - 60_000).text).toBe('00:01:00')
  })
  it('截止相等或过去显示已超时，终态停止倒计时而不被当前日期误标超时', () => {
    for (const 阶段 of ['待审核', '待推单', '待发货', '异常'] as 订单处理状态[]) {
      expect(计算剩余发货时间(截止, 阶段, 截止时刻)).toEqual({ kind: 'overdue', text: '已超时' })
      expect(计算剩余发货时间(截止, 阶段, 截止时刻 + 1).kind).toBe('overdue')
    }
    expect(计算剩余发货时间(截止, '已发货', 截止时刻 + 1)).toEqual({ kind: 'complete', text: '已发货' })
    expect(计算剩余发货时间(截止, '不发货', 截止时刻 + 1)).toEqual({ kind: 'complete', text: '无需发货' })
  })
  it('缺失与未知时间不生成虚构期限，当前时刻无效也不能判超时', () => {
    expect(计算剩余发货时间(undefined, '待审核', 截止时刻)).toEqual({ kind: 'missing', text: '—' })
    expect(计算剩余发货时间('2026-09-13 18:00:00', '待审核', 截止时刻)).toEqual({ kind: 'invalid', text: '时间待核实' })
    expect(计算剩余发货时间(截止, '待审核', Number.NaN)).toEqual({ kind: 'invalid', text: '时间待核实' })
  })
})
