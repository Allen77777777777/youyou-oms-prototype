export function 展示处理原因(原文: string | undefined): string {
  return 显示替换.reduce((文案, [原值, 显示值]) => 文案.split(原值).join(显示值), 原文 ?? '')
}

/** 只读提示；未查到请求不是截单成功，历史已取消的路径也不能继续提示等待出库。 */
export function 获取仓库结束提示(行: 作业行): { 建议: string; 原因: string } | undefined {
  if (!['待推单', '待发货'].includes(行.stage)) return undefined
  const 来源 = 行.fulfillment ? 共享订单.value.filter(订单 => 订单.fulfillmentOrders.some(项 => 项.fulfillmentOrderNo === 行.fulfillment!.fulfillmentOrderNo)) : [行.order]
  const 完整来源 = 来源.length ? 来源 : [行.order]
  const 全部执行 = [...完整来源.flatMap(订单关联仓库执行), ...(行.execution ? [行.execution] : [])]
  if (!全部执行.length || 全部执行.some(项 => 项.状态 !== '已取消' || 项.待核查)) return undefined
  // 仍有另一个尚未提交的有效方案时，不能把已结束的旧路径作为整单结束。
  if (完整来源.some(订单 => 订单.fulfillmentOrders.some(项 => 项.isActive && !全部执行.some(执行 => 执行.履约单号 === 项.fulfillmentOrderNo)))) return undefined
  if (完整来源.some(订单 => 零出库阻断原因(订单).length)) return { 建议: '请核对已出库及剩余发货范围', 原因: '仓库已截单，实际出库及剩余范围仍需核实' }
  if (完整来源.some(有共享发货路径)) return { 建议: '请专项核对共享履约的后续处理', 原因: '仓库已截单，请核对全部来源订单及发货范围' }
  return { 建议: '请复核后退回待审核或操作不发货', 原因: '仓库已确认截单成功，原执行已结束' }
}

export function 获取处理建议(行: 作业行, 阻断: string[], 标发状态?: string): string {
  const 结束提示 = 获取仓库结束提示(行)
  if (结束提示) return 结束提示.建议
  if (行.stage === '待审核') return 阻断.length ? '请核对拦截原因，补齐发货条件' : '请审核通过'
  if (行.stage === '待推单') return 行.execution?.状态 === '下单失败' ? '请查看出库单，核查失败原因' : 行.execution ? '请同步仓库状态，核查原请求' : 阻断.length ? '请核对拦截原因，补齐推单条件' : '请推单，等待仓库接单结果'
  if (行.stage === '待发货') return 行.execution?.原因 ? '请查看出库单，核查仓库执行情况' : '请跟进仓库发货，等待出库结果'
  if (行.stage === '已发货') return 标发状态 === '标发失败' ? '请查看订单标发，核查失败原因' : '请查看订单标发，核对平台回传结果'
  return 行.stage === '异常' ? '请人工复核异常原因及仓库执行' : '请查看不发货原因及执行记录'
}
