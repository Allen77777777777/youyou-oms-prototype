function editor(options: { body?: string; conversation?: Conversation; uncertain?: boolean; templateContext?: TemplateContext; purpose?: 'mailbox' | 'review-contact'; realAnnotations?: boolean } = {}) {
  const draft = reactive<ReplyDraft>({ body: options.body ?? '', attachments: [] })
  const wrapper = mount(ReplyEditor, {
    props: { conversation: options.conversation ?? createConversations()[0]!, draft, mode: 'reply', sending: false, uncertain: options.uncertain ?? false, templateContext: options.templateContext, purpose: options.purpose },
    attachTo: document.body,
    global: { directives: { prototype: options.realAnnotations ? 原型标注指令 : {} }, stubs: { ElDialog: DialogShell } },
  })
  wrappers.push(wrapper)
  return { wrapper, draft }
}
function button(wrapper: VueWrapper, label: string, index = 0) {
  const target = wrapper.findAll('button').filter(item => item.text().trim() === label)[index]
  if (!target) throw new Error(`没有找到按钮 ${label}`)
  return target
}
