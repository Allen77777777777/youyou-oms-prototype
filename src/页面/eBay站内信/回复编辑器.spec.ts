async function setRich(wrapper: VueWrapper, text: string) {
  const plain = wrapper.find('.reply-body textarea')
  if (plain.exists()) await plain.setValue(text)
  else { const box = wrapper.get('[contenteditable="true"]'); box.element.innerHTML = plainTextToHtml(text); await box.trigger('input') }
  await nextTick()
}
async function selectPlain(wrapper: VueWrapper, start: number, end = start) {
  const box = wrapper.get<HTMLTextAreaElement>('.reply-body textarea')
  box.element.setSelectionRange(start, end)
  await box.trigger('mouseup')
}
async function preview(wrapper: VueWrapper, id: string) { await wrapper.get(`[data-template-id="${id}"]`).trigger('click') }

