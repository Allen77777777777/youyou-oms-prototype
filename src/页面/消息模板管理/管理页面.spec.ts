import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount, type VueWrapper } from '@vue/test-utils'
import { ElMessage, ElMessageBox } from 'element-plus'
import TemplatePage from './消息模板管理页面.vue'
import { resetTemplateSession, saveTemplate, templateSession } from './模型'
import { MAX_REPLY_ATTACHMENTS } from '../eBay站内信/模型'

const Overlay = { props: ['modelValue', 'title', 'alignCenter'], emits: ['update:modelValue'], template: '<section v-if="modelValue" class="test-overlay" :data-title="title" :data-align-center="alignCenter"><slot/><footer><slot name="footer"/></footer></section>' }
let wrapper: VueWrapper
function button(text: string) { const node = wrapper.findAll('button').find(item => item.text().trim() === text); if (!node) throw new Error(`未找到按钮：${text}`); return node }
function row(title: string) { const node = wrapper.findAll('.template-table .el-table__row').find(item => item.find('.template-name').text() === title); if (!node) throw new Error(`未找到内容：${title}`); return node }
async function rowAction(title: string, action: string) { await row(title).findAll('button').find(item => item.text().trim() === action)!.trigger('click'); await flushPromises() }
async function richHtml(value: string) {
  const input = wrapper.get('[contenteditable="true"][aria-label="模板正文"]')
  input.element.innerHTML = value
  await input.trigger('input'); await flushPromises()
  return input
}
async function selectRichText(start: number, end: number) {
  const editor = wrapper.get('[contenteditable="true"][aria-label="模板正文"]')
  ;(editor.element as HTMLElement).focus()
  const node = editor.element.querySelector('p')!.firstChild!
  const range = document.createRange(); range.setStart(node, start); range.setEnd(node, end)
  const selection = window.getSelection()!; selection.removeAllRanges(); selection.addRange(range)
  await editor.trigger('mouseup')
}
async function filesSelected(files: File[]) {
  const input = wrapper.get('input[aria-label="选择模板附件"]')
  Object.defineProperty(input.element, 'files', { configurable: true, value: files })
  await input.trigger('change'); await flushPromises()
}
beforeEach(() => {
  resetTemplateSession()
  for (const action of ['success', 'warning', 'info'] as const) vi.spyOn(ElMessage, action).mockImplementation(() => ({ close: vi.fn() }))
  wrapper = mount(TemplatePage, { attachTo: document.body, global: { stubs: { ElDialog: Overlay }, directives: { prototype: {} } } })
})
afterEach(() => { wrapper.unmount(); document.body.innerHTML = ''; window.getSelection()?.removeAllRanges(); vi.restoreAllMocks() })

describe('消息模板管理页面', () => {
  it('新增放在筛选下方独立操作行，使用居中弹窗且没有变量管理入口', async () => {
    expect(wrapper.findAll('button').some(item => ['变量管理', '新增变量', '保存变量'].includes(item.text().trim()))).toBe(false)
    expect(wrapper.get('.template-actions').element.previousElementSibling).toBe(wrapper.get('.template-filters').element)
    expect(wrapper.get('.template-actions').text()).toBe('新增站内信模板变更记录')
    await button('新增站内信模板').trigger('click')
    expect(wrapper.get('.template-editor-dialog').attributes('data-align-center')).toBe('')
    expect(wrapper.find('.el-drawer').exists()).toBe(false)
    expect(wrapper.find('input[aria-label="模板名称"]').exists()).toBe(true)
    expect(wrapper.find('input[aria-label="内部参考标题"]').exists()).toBe(true)
    expect(wrapper.find('[contenteditable="true"][aria-label="模板正文"]').exists()).toBe(true)
    expect(wrapper.find('[aria-label="模板附件"]').exists()).toBe(true)
    expect(wrapper.find('[aria-label="段落格式"]').exists()).toBe(true)
    expect(wrapper.find('[aria-label="字号"]').exists()).toBe(true)
    expect(wrapper.find('[aria-label="加粗"]').exists()).toBe(true)
    expect(wrapper.findAll('.template-variable-picker button').map(item => item.text())).toEqual(['买家 ID', '关联订单号', '商品名称', '跟踪号', '平台商品名称', '平台商品SKU'])
    expect(wrapper.find('[aria-label="插入变量 店铺名称"]').exists()).toBe(false)
    expect(wrapper.find('[aria-label="插入变量 客服署名"]').exists()).toBe(false)
  })
  it('模板表单不显示保存后启用，停用模板编辑保存后直接启用', async () => {
    const source = templateSession.templates.find(item => item.kind === 'message')!
    source.enabled = false
    await rowAction(source.title, '编辑')
    expect(wrapper.text()).not.toContain('保存后启用')
    await button('保存').trigger('click'); await flushPromises()
    expect(source.enabled).toBe(true)
  })
  it('类型页签隔离，查询前不应用草稿，常用语只编辑名称与正文', async () => {
    expect(wrapper.findAll('.template-table .el-table__row')).toHaveLength(5)
    await wrapper.get('input[aria-label="模板搜索内容"]').setValue('按订单跟进')
    expect(wrapper.findAll('.template-table .el-table__row')).toHaveLength(5)
    await button('查询').trigger('click')
    expect(wrapper.findAll('.template-table .el-table__row')).toHaveLength(1)
    await button('重置').trigger('click'); await button('常用语').trigger('click')
    expect(wrapper.findAll('.template-table .el-table__row')).toHaveLength(3)
    await button('新增常用语').trigger('click')
    expect(wrapper.find('input[aria-label="内部参考标题"]').exists()).toBe(false)
    expect(wrapper.find('[aria-label="模板附件"]').exists()).toBe(false)
    expect(wrapper.find('[contenteditable="true"]').exists()).toBe(false)
    await wrapper.get('input[aria-label="模板名称"]').setValue('新的礼貌结语')
    const body = wrapper.get('textarea[aria-label="模板正文"]')
    await body.setValue('Hello NAME')
    ;(body.element as HTMLTextAreaElement).setSelectionRange(6, 10); await body.trigger('select')
    await wrapper.get('[aria-label="插入变量 买家 ID"]').trigger('click')
    expect((body.element as HTMLTextAreaElement).value).toBe('Hello {{buyerId}}')
    await button('保存').trigger('click')
    const saved = templateSession.templates.find(item => item.title === '新的礼貌结语')!
    expect(saved).toMatchObject({ kind: 'phrase', enabled: true, body: 'Hello {{buyerId}}' })
    expect(saved.subject).toBeUndefined(); expect(saved.attachments).toBeUndefined()
  })
  it('标题与正文按各自选区插入变量，示例预览合并缺值且不改原草稿', async () => {
    await button('新增站内信模板').trigger('click')
    await wrapper.get('input[aria-label="模板名称"]').setValue('预览变量模板')
    const subject = wrapper.get('input[aria-label="内部参考标题"]')
    await subject.setValue('Order PLACEHOLDER')
    ;(subject.element as HTMLInputElement).setSelectionRange(6, 17); await subject.trigger('select')
    await wrapper.get('[aria-label="插入变量 关联订单号"]').trigger('click')
    expect((subject.element as HTMLInputElement).value).toBe('Order {{orderNo}}')
    const editor = await richHtml('<p>Hello PLACEHOLDER</p>')
    await selectRichText(6, 17)
    await wrapper.get('[aria-label="插入变量 买家 ID"]').trigger('click'); await flushPromises()
    expect(editor.text()).toBe('Hello {{buyerId}}')
    expect((subject.element as HTMLInputElement).value).toBe('Order {{orderNo}}')
    await button('预览内容').trigger('click')
    expect(wrapper.get('.template-preview-warning').text()).toContain('买家 ID')
    expect(wrapper.get('.template-preview-warning').text()).toContain('关联订单号')
    await wrapper.get('input[aria-label="预览 买家 ID"]').setValue('buyer_demo_preview')
    await wrapper.get('input[aria-label="预览 关联订单号"]').setValue('DEMO-PREVIEW-01')
    expect(wrapper.get('.template-preview-subject h3').text()).toBe('Order DEMO-PREVIEW-01')
    expect(wrapper.get('.template-preview-body').text()).toBe('Hello buyer_demo_preview')
    expect(editor.text()).toBe('Hello {{buyerId}}')
    expect((subject.element as HTMLInputElement).value).toBe('Order {{orderNo}}')
    await button('关闭').trigger('click')
    await button('保存').trigger('click')
    expect(templateSession.templates.find(item => item.title === '预览变量模板')).toMatchObject({ subject: 'Order {{orderNo}}', body: 'Hello {{buyerId}}' })
  })
  it('富文本格式、内部参考标题与附件一起预览保存，移除附件只改当前编辑草稿', async () => {
    await button('新增站内信模板').trigger('click')
    await wrapper.get('input[aria-label="模板名称"]').setValue('完整内容模板')
    await wrapper.get('input[aria-label="内部参考标题"]').setValue('Shipping update')
    await richHtml('<h2>Delivery details</h2><p><strong>Please check</strong> <span style="font-size: 20px">the parcel</span></p>')
    await filesSelected([new File(['sample pdf'], 'shipping-guide.pdf', { type: 'application/pdf' })])
    expect(wrapper.get('.template-attachments .template-attachment-list').text()).toContain('shipping-guide.pdf')
    await button('预览内容').trigger('click')
    expect(wrapper.get('.template-preview-subject h3').text()).toBe('Shipping update')
    expect(wrapper.get('.template-preview-body h2').text()).toBe('Delivery details')
    expect(wrapper.get('.template-preview-body strong').text()).toBe('Please check')
    expect(wrapper.get('.template-preview-body span').attributes('style')).toContain('20px')
    expect(wrapper.get('[aria-label="预览附件"]').text()).toContain('shipping-guide.pdf')
    await button('关闭').trigger('click'); await button('保存').trigger('click')
    const saved = templateSession.templates.find(item => item.title === '完整内容模板')!
    expect(saved.subject).toBe('Shipping update')
    expect(saved.bodyHtml).toContain('<h2>Delivery details</h2>')
    expect(saved.bodyHtml).toContain('<strong>Please check</strong>')
    expect(saved.body).not.toContain('<')
    expect(saved.attachments).toHaveLength(1)
    await rowAction(saved.title, '编辑')
    await wrapper.get('[aria-label="移除附件 shipping-guide.pdf"]').trigger('click')
    expect(wrapper.find('.template-attachments .template-attachment-list').exists()).toBe(false)
    expect(saved.attachments).toHaveLength(1)
    await button('取消').trigger('click')
    expect(saved.attachments).toHaveLength(1)
  })
  it('内部参考标题可留空保存，未知变量及附件数量类型和大小仍受控', async () => {
    await button('新增站内信模板').trigger('click')
    await wrapper.get('input[aria-label="模板名称"]').setValue('校验模板')
    await richHtml('<p>Valid body</p>')
    await button('保存').trigger('click')
    expect(templateSession.templates.find(item => item.title === '校验模板')).toMatchObject({ subject: '', body: 'Valid body' })
    await rowAction('校验模板', '编辑')
    await wrapper.get('input[aria-label="内部参考标题"]').setValue('Hello {{shopName}}')
    await button('保存').trigger('click')
    expect(wrapper.get('.template-edit-content .template-error').text()).toContain('未定义')
    await wrapper.get('input[aria-label="内部参考标题"]').setValue('Valid subject')
    await filesSelected([new File(['script'], 'unsupported.svg', { type: 'image/svg+xml' })])
    expect(wrapper.get('.template-edit-content .template-error').text()).toContain('PNG、JPG 或 PDF')
    const tooLarge = new File(['big'], 'too-large.pdf', { type: 'application/pdf' })
    Object.defineProperty(tooLarge, 'size', { value: 5 * 1024 * 1024 + 1 })
    await filesSelected([tooLarge])
    expect(wrapper.get('.template-edit-content .template-error').text()).toContain('5 MB')
    await filesSelected(Array.from({ length: MAX_REPLY_ATTACHMENTS + 1 }, (_, index) => new File(['file'], `${index}.png`, { type: 'image/png' })))
    expect(wrapper.get('.template-edit-content .template-error').text()).toContain(`${MAX_REPLY_ATTACHMENTS} 个附件`)
    expect(wrapper.find('.template-attachments .template-attachment-list').exists()).toBe(false)
    expect(templateSession.templates.find(item => item.title === '校验模板')).toMatchObject({ subject: '', body: 'Valid body' })
  })
  it('模板富文本超限保存不截断，常用语与计数统一2000字符', async () => {
    await button('新增站内信模板').trigger('click')
    await wrapper.get('input[aria-label="模板名称"]').setValue('长度边界模板')
    await richHtml(`<p>${'a'.repeat(2001)}</p>`)
    expect(wrapper.get('.template-body-meta').text()).toContain('2001 / 2000')
    await button('保存').trigger('click')
    expect(wrapper.get('.template-edit-content .template-error').text()).toContain('2000')
    expect(wrapper.get('[contenteditable="true"]').text()).toHaveLength(2001)
    await richHtml(`<p>${'a'.repeat(2000)}</p>`)
    await button('保存').trigger('click')
    expect(templateSession.templates.find(item => item.title === '长度边界模板')?.body).toHaveLength(2000)
    await button('常用语').trigger('click'); await button('新增常用语').trigger('click')
    expect(wrapper.get('textarea[aria-label="模板正文"]').attributes('maxlength')).toBeUndefined()
    expect(wrapper.get('.template-body-meta').text()).toContain('0 / 2000')
    await wrapper.get('input[aria-label="模板名称"]').setValue('超长常用语')
    await wrapper.get('textarea[aria-label="模板正文"]').setValue('b'.repeat(2001))
    await button('保存').trigger('click')
    expect(wrapper.get('.template-edit-content .template-error').text()).toContain('2000')
    expect((wrapper.get('textarea[aria-label="模板正文"]').element as HTMLTextAreaElement).value).toHaveLength(2001)
  })
  it('编辑取消不改共享内容，复制标题正文附件深隔离且默认停用', async () => {
    const creation = saveTemplate({ kind: 'message', title: '带附件源模板', subject: 'Original subject', body: 'Original body', bodyHtml: '<h3>Original body</h3>', attachments: [{ id: 'original-file', name: 'original.pdf', size: 10, type: 'application/pdf', source: 'local' }], enabled: true })
    const source = creation.template!; expect(source).toBeDefined(); await flushPromises()
    await rowAction(source.title, '编辑')
    await wrapper.get('input[aria-label="内部参考标题"]').setValue('Unsaved subject')
    await richHtml('<p>Unsaved body</p>')
    await wrapper.get('[aria-label="移除附件 original.pdf"]').trigger('click')
    await button('取消').trigger('click')
    expect(source).toMatchObject({ subject: 'Original subject', body: 'Original body' }); expect(source.attachments).toHaveLength(1)
    await rowAction(source.title, '复制')
    const copy = templateSession.templates.find(item => item.title === `${source.title}（副本）`)!
    expect(copy.enabled).toBe(false); expect(copy.attachments?.[0]).not.toBe(source.attachments?.[0])
    await rowAction(copy.title, '编辑')
    await wrapper.get('input[aria-label="内部参考标题"]').setValue('Copy subject')
    await richHtml('<p>Copy body</p>')
    await wrapper.get('[aria-label="移除附件 original.pdf"]').trigger('click')
    await button('保存').trigger('click')
    expect(copy).toMatchObject({ subject: 'Copy subject', body: 'Copy body', attachments: [], enabled: true })
    expect(source).toMatchObject({ subject: 'Original subject', body: 'Original body' }); expect(source.attachments).toHaveLength(1)
    await rowAction(copy.title, '停用'); expect(copy.enabled).toBe(false)
    await rowAction(copy.title, '启用'); expect(copy.enabled).toBe(true)
    const confirm = vi.spyOn(ElMessageBox, 'confirm').mockRejectedValueOnce('cancel')
    await rowAction(copy.title, '删除'); expect(templateSession.templates.some(item => item.id === copy.id)).toBe(true)
    confirm.mockResolvedValue('confirm' as Awaited<ReturnType<typeof ElMessageBox.confirm>>)
    await rowAction(copy.title, '删除'); expect(templateSession.templates.some(item => item.id === copy.id)).toBe(false)
  })
})
